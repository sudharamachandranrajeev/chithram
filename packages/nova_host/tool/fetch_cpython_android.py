#!/usr/bin/env python3
"""Lays out CPython's official Android build for the nova_host Android plugin.

Source: python.org release 3.14.x "python-<ver>-<arch>-linux-android.tar.gz"
(PEP 738; PSF licence) for arm64-v8a and x86_64. python.org publishes no armv7
build, so armeabi-v7a uses "python-<ver>-arm-linux-androideabi.tar.gz", built from
the same CPython tag with CPython's own Android/android.py by
.github/workflows/cpython-android.yml and published as an asset of this repo's
`cpython-android-<ver>` pre-release. Every tarball is pinned by sha256 here.

Output (all git-ignored, regenerated by Gradle `prepareCpythonAndroid`):
  android/src/main/jniLibs/<abi>/libpython3.14.so          the interpreter
  android/src/main/jniLibs/<abi>/libpymod_<name>.so        extension modules we ship
  android/src/main/jniLibs/<abi>/libnova_stdlib.so         STORED zip of the stripped stdlib (.py)
  android/src/main/jniLibs/<abi>/libnova_runtime.so        STORED zip of python/nova/runtime
  android/cpython/<abi>/include/python3.14/                headers for the JNI glue
Zips are stored, not deflated, because the interpreter imports `encodings` from
them before `zlib` can be loaded. Needs only the Python standard library.
"""
import hashlib
import io
import os
import shutil
import sys
import tarfile
import urllib.request
import zipfile

VERSION = "3.14.8"
PYVER = "3.14"
PYTHON_ORG = "https://www.python.org/ftp/python/%s/" % VERSION
SELF_BUILT = "https://github.com/sudharamachandranrajeev/chithram/releases/download/cpython-android-%s/" % VERSION
ABIS = {
    # android ABI -> (download base, tarball name, sha256 of the tarball, pinned here after download)
    "arm64-v8a": (PYTHON_ORG, "python-%s-aarch64-linux-android.tar.gz" % VERSION,
                  "11324313957da3736f44e90257304d288864321a4dd376ed0cc35a54eacf9a33"),
    "armeabi-v7a": (SELF_BUILT, "python-%s-arm-linux-androideabi.tar.gz" % VERSION,
                    "33b09ee5e932bbf2a048f914ff8e56908e02b791bbff26c9dac92bffed70d8ff"),
    "x86_64": (PYTHON_ORG, "python-%s-x86_64-linux-android.tar.gz" % VERSION,
               "58eb3b2d76ef57e076985a0a6b093cf08906d65ea4ab78cccc6d894d4250c972"),
}

# Extension modules the plugin runtime may import (no ssl/sqlite/ctypes/curses/tests).
EXT_KEEP = {
    "array", "binascii", "_bisect", "_blake2", "_bz2", "cmath", "_csv", "_decimal", "_elementtree",
    "fcntl", "_heapq", "_hmac", "_json", "_lzma", "math", "_md5", "mmap", "_multibytecodec", "_pickle",
    "_posixsubprocess", "pyexpat", "_queue", "_random", "resource", "select", "_sha1", "_sha2",
    "_sha3", "_socket", "_statistics", "_struct", "termios", "unicodedata", "zlib", "_zoneinfo",
}
DROP_DIRS = {
    "test", "tests", "idlelib", "tkinter", "turtledemo", "ensurepip", "pydoc_data", "lib2to3",
    "ctypes", "curses", "dbm", "sqlite3", "distutils", "__pycache__", "site-packages", "venv",
    "unittest", "asyncio", "multiprocessing", "wsgiref", "xmlrpc", "_pyrepl", "lib-dynload",
    "zoneinfo", "__phello__",
}
DROP_FILES = {
    "turtle.py", "this.py", "antigravity.py", "pydoc.py", "pdb.py", "doctest.py", "profile.py",
    "cProfile.py", "pstats.py", "trace.py", "tracemalloc.py", "timeit.py", "tabnanny.py",
    "modulefinder.py", "rlcompleter.py", "pty.py", "tty.py", "webbrowser.py", "mailbox.py",
    "imaplib.py", "poplib.py", "smtplib.py", "ftplib.py", "wave.py", "shelve.py", "zipapp.py",
    "build-details.json", "LICENSE.txt", "_pyio.py", "_osx_support.py", "_aix_support.py",
    "_ios_support.py", "_apple_support.py", "pyclbr.py", "sched.py", "netrc.py", "plistlib.py",
}
# encodings: keep the common ones, drop CJK / legacy code pages.
ENC_KEEP_PREFIX = ("__init__", "aliases", "ascii", "latin_1", "utf_", "cp1252", "cp437", "idna",
                   "punycode", "iso8859_1", "iso8859_2", "iso8859_15", "raw_unicode_escape",
                   "unicode_escape", "charmap", "hex_codec", "base64_codec", "quopri_codec",
                   "uu_codec", "zlib_codec", "bz2_codec", "rot_13", "mbcs", "oem", "undefined",
                   "cp1250", "cp1251", "koi8_r", "gbk", "big5", "shift_jis", "euc_jp", "euc_kr")
ENC_DROP_FULL = {"gbk", "big5", "shift_jis", "euc_jp", "euc_kr"}  # need the CJK codecs we do not ship


def here():
    return os.path.dirname(os.path.abspath(__file__))


def fetch(abi, cache):
    base, name, sha = ABIS[abi]
    dst = os.path.join(cache, name)
    if not os.path.exists(dst) or sha256(dst) != sha:
        os.makedirs(cache, exist_ok=True)
        print("downloading", base + name, file=sys.stderr)
        urllib.request.urlretrieve(base + name, dst)
    got = sha256(dst)
    if got != sha:
        sys.exit("sha256 mismatch for %s: %s != %s" % (dst, got, sha))
    return dst


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def safe_extract(tar, dest):
    base = os.path.realpath(dest)
    for m in tar.getmembers():
        if not os.path.realpath(os.path.join(dest, m.name)).startswith(base + os.sep) and m.name != ".":
            sys.exit("unsafe path in tarball: " + m.name)
    tar.extractall(dest)


def stdlib_zip(libdir, out):
    n = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_STORED) as z:
        for root, dirs, files in os.walk(libdir):
            rel = os.path.relpath(root, libdir)
            dirs[:] = sorted(d for d in dirs if d not in DROP_DIRS and not d.startswith("config-"))
            for f in sorted(files):
                if not f.endswith(".py") or f in DROP_FILES or f.startswith("_sysconfig"):
                    continue
                if rel == "encodings":
                    stem = f[:-3]
                    if stem in ENC_DROP_FULL or not stem.startswith(ENC_KEEP_PREFIX):
                        continue
                arc = f if rel == "." else os.path.join(rel, f)
                z.write(os.path.join(root, f), arc.replace(os.sep, "/"))
                n += 1
        # encodings subpackage lives under DROP_DIRS-free path; nothing else to add
    return n


def runtime_zip(out):
    src = os.path.join(here(), "..", "..", "..", "python", "nova", "runtime")
    src = os.path.abspath(src)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_STORED) as z:
        for root, dirs, files in os.walk(src):
            dirs[:] = sorted(d for d in dirs if d != "__pycache__")
            for f in sorted(files):
                if f.endswith(".py"):
                    z.write(os.path.join(root, f), os.path.relpath(os.path.join(root, f), src).replace(os.sep, "/"))


def main():
    android = os.path.abspath(os.path.join(here(), "..", "android"))
    cache = os.environ.get("NOVA_CPYTHON_CACHE", os.path.join(android, "build", "cpython-cache"))
    stamp_inputs = [os.path.abspath(__file__)]
    for abi in ABIS:
        tgz = fetch(abi, cache)
        jni = os.path.join(android, "src", "main", "jniLibs", abi)
        inc = os.path.join(android, "cpython", abi, "include")
        tmp = os.path.join(cache, "x-" + abi)
        shutil.rmtree(tmp, ignore_errors=True)
        with tarfile.open(tgz) as t:
            safe_extract(t, tmp)
        prefix = os.path.join(tmp, "prefix")
        shutil.rmtree(jni, ignore_errors=True)
        shutil.rmtree(os.path.dirname(inc), ignore_errors=True)
        os.makedirs(jni)
        shutil.copy2(os.path.join(prefix, "lib", "libpython%s.so" % PYVER), jni)
        dyn = os.path.join(prefix, "lib", "python" + PYVER, "lib-dynload")
        kept = []
        for f in sorted(os.listdir(dyn)):
            name = f.split(".")[0]
            if name in EXT_KEEP:
                shutil.copy2(os.path.join(dyn, f), os.path.join(jni, "libpymod_%s.so" % name))
                kept.append(name)
        n = stdlib_zip(os.path.join(prefix, "lib", "python" + PYVER), os.path.join(jni, "libnova_stdlib.so"))
        runtime_zip(os.path.join(jni, "libnova_runtime.so"))
        shutil.copytree(os.path.join(prefix, "include"), inc)
        total = sum(os.path.getsize(os.path.join(jni, f)) for f in os.listdir(jni))
        print("%s: %d stdlib files, %d extension modules, %.1f MB in jniLibs" % (abi, n, len(kept), total / 1e6))
        shutil.rmtree(tmp, ignore_errors=True)
    lic = os.path.join(android, "src", "main", "assets", "nova")
    os.makedirs(lic, exist_ok=True)


if __name__ == "__main__":
    main()
