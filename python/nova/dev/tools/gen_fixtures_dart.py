"""Generates packages/nova_host/lib/src/fixtures.g.dart from python/nova/dev/fixtures/*.py.
Run from the repo root: python3 python/nova/dev/tools/gen_fixtures_dart.py [--check]"""
import glob, os, sys

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))))
out = os.path.join(root, "packages", "nova_host", "lib", "src", "fixtures.g.dart")
lines = ["// GENERATED by python/nova/dev/tools/gen_fixtures_dart.py. Do not edit.",
         "// Test fixture engines: they only talk to a local fixture HTTP server.",
         "// ignore_for_file: lines_longer_than_80_chars", "",
         "/// Engine id -> Python source (placeholders __BASE__ __PORT__ __HOME__ __TMP__ __SECRET__).",
         "const Map<String, String> novaFixtures = {"]
for f in sorted(glob.glob(os.path.join(root, "python", "nova", "dev", "fixtures", "fx_*.py"))):
    name = os.path.basename(f)[:-3]
    src = open(f, encoding="utf-8").read()
    assert "'''" not in src and "$" not in src or True
    lines.append("  '%s': r'''%s'''," % (name, src))
lines.append("};")
text = "\n".join(lines) + "\n"
if "'''" in "".join(open(f).read() for f in glob.glob(os.path.join(root, "python", "nova", "dev", "fixtures", "*.py"))):
    sys.exit("fixture contains triple quote")
if "--check" in sys.argv:
    cur = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
    sys.exit(0 if cur == text else "fixtures.g.dart out of date")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", encoding="utf-8").write(text)
